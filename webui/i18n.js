  var current = 'fr';

  /** Langue courante ('fr' | 'en'). */
  function lang() { return current; }

  /** Pose la langue. Toute valeur inconnue retombe sur le français. */
  function setLang(l) {
    var next = (l === 'en') ? 'en' : 'fr';
    var changed = next !== current;
    current = next;
    return changed;
  }

  /** Traduit une chaîne complète. Inconnue du catalogue = rendue telle quelle. */
  function tr(s) {
    if (current === 'fr' || typeof s !== 'string' || s === '') { return s; }
    var v = EN[s];
    return (typeof v === 'string' && v !== '') ? v : s;
  }

  /** Traduit un gabarit puis substitue {0}, {1}, … par les arguments. */
  function trf(tpl) {
    var args = Array.prototype.slice.call(arguments, 1);
    return tr(tpl).replace(/\{(\d+)\}/g, function (m, i) {
      var v = args[+i];
      return (v === undefined || v === null) ? '' : String(v);
    });
  }

  /** Vrai si la chaîne a une traduction (utilisé par les outils, pas par l'UI). */
  function has(s) { return Object.prototype.hasOwnProperty.call(EN, s); }

  return { tr: tr, trf: trf, lang: lang, setLang: setLang, has: has, catalog: EN };
